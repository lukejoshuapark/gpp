package driver

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// A SourcePackage lists the source files of a package, as the go command
// sees them, without loading or type-checking it.
type SourcePackage struct {
	ImportPath string
	Dir        string
	Main       bool // in the main module (or not in a module)
	// Files are the package's .go and .gpp files, test files included,
	// in the go command's order; XFiles are its external test files.
	Files  []string
	XFiles []string
	Error  string // set if the package has no files and could not be loaded
}

// ListSources lists the packages matching patterns with their .go and .gpp
// files. Unlike Load, it does not look at dependencies and does not need
// the packages to compile.
func ListSources(cfg *Config, patterns ...string) ([]*SourcePackage, error) {
	if cfg.Dir == "" {
		wd, err := os.Getwd()
		if err != nil {
			return nil, err
		}
		cfg.Dir = wd
	}
	dir, err := filepath.Abs(cfg.Dir)
	if err != nil {
		return nil, err
	}
	cfg.Dir = dir
	if len(patterns) == 0 {
		patterns = []string{"."}
	}
	l := newLoader(cfg, patterns)
	l.noDeps = true
	list, err := l.goList(patterns)
	if err != nil {
		return nil, err
	}
	var pkgs []*SourcePackage
	for _, lp := range list {
		sp := &SourcePackage{ImportPath: lp.ImportPath, Dir: lp.Dir, Main: lp.Module == nil || lp.Module.Main}
		sp.Files = l.sourceFiles(lp.Dir, lp.GoFiles, lp.CgoFiles, lp.TestGoFiles)
		sp.XFiles = l.sourceFiles(lp.Dir, lp.XTestGoFiles)
		if lp.Error != nil && len(sp.Files)+len(sp.XFiles) == 0 {
			sp.Error = strings.TrimSpace(lp.Error.Err)
		}
		pkgs = append(pkgs, sp)
	}
	return pkgs, nil
}

// sourceFiles makes the files go list reported absolute, replacing stubs
// with their .gpp files and dropping Go files generated by gpp gen.
func (l *loader) sourceFiles(dir string, lists ...[]string) []string {
	var files []string
	for _, f := range slices.Concat(lists...) {
		if !filepath.IsAbs(f) {
			f = filepath.Join(dir, f)
		}
		if gpp, ok := l.stubs[f]; ok {
			f = gpp
		} else if gen := generatedFrom(f); gen != "" && fileExists(gen) {
			continue
		}
		files = append(files, f)
	}
	return files
}
