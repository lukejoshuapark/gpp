// Package lower translates type-checked G++ files to Go.
//
// Lowering rewrites the G++ constructs in a file's syntax tree into plain
// Go constructs (in place), then prints the tree with //line directives
// so that the Go compiler's messages and stack traces point at the .gpp
// source:
//
//	cond ? a : b   func() T { if cond { return a }; return b }()
//	                (or an if statement when a branch needs statements)
//	f()?           v, err := f(); if err != nil { return zero, err }
//	                ahead of the statement, then v in its place
//	x => e         func(x T) R { return e }
//
// When a ? must run before other operands of the same statement, those
// operands are evaluated into temporaries first, keeping Go's
// left-to-right order of calls.
package lower

import (
	"bytes"
	"fmt"
	"go/constant"
	"go/token"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"gpp/ast"
	"gpp/printer"
	"gpp/types"
)

// tempPrefix starts the names of temporaries and imports added by
// lowering. G++ reserves identifiers with this prefix.
const tempPrefix = "__gpp_"

// An Error is a problem lowering a file (rare: most are caught by type
// checking).
type Error struct {
	Pos token.Position
	Msg string
}

func (e *Error) Error() string { return fmt.Sprintf("%s: %s", e.Pos, e.Msg) }

// File lowers the G++ file f of package pkg, modifying its syntax tree,
// and returns the Go source.
func File(fset *token.FileSet, pkg *types.Package, info *types.Info, f *ast.File) ([]byte, []*Error) {
	l := &lowerer{
		fset:    fset,
		pkg:     pkg,
		info:    info,
		file:    f,
		imports: map[string]string{},
		tuples:  map[*ast.Ident][]ast.Expr{},
		wrapped: map[*ast.BlockStmt]bool{},
	}
	for _, d := range f.Decls {
		l.decl(d)
	}
	l.addImports()
	if len(l.errs) > 0 {
		return nil, l.errs
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gpp from %s. DO NOT EDIT.\n\n", filepath.Base(fset.Position(f.Pos()).Filename))
	cfg := printer.Config{Mode: printer.UseSpaces | printer.TabIndent | printer.SourcePos, Tabwidth: 8}
	if err := cfg.Fprint(&buf, fset, f); err != nil {
		return nil, []*Error{{Pos: fset.Position(f.Pos()), Msg: "printing lowered file: " + err.Error()}}
	}
	if len(l.generated) > 0 {
		fmt.Fprintf(&buf, "\n//line %s.generated:1\n", fset.Position(f.Pos()).Filename)
		for _, g := range l.generated {
			buf.WriteString(g)
		}
	}
	return buf.Bytes(), nil
}

type lowerer struct {
	fset    *token.FileSet
	pkg     *types.Package
	info    *types.Info
	file    *ast.File
	imports map[string]string // import path -> name, for imports lowering adds
	ntemp   int
	errs    []*Error
	fn      *types.Signature // signature of the innermost enclosing function

	// tuples maps placeholder identifiers to the values of a lowered
	// multi-valued x? expression, which its context (an assignment,
	// return or call) spreads out.
	tuples map[*ast.Ident][]ast.Expr
	// wrapped records blocks lowering introduced around a statement, so
	// labels move to the statement inside.
	wrapped map[*ast.BlockStmt]bool
	// generated holds Go source lowering adds after the file (enum
	// methods).
	generated []string
}

func (l *lowerer) errorf(pos token.Pos, format string, args ...any) {
	l.errs = append(l.errs, &Error{Pos: l.fset.Position(pos), Msg: fmt.Sprintf(format, args...)})
}

func (l *lowerer) temp(pos token.Pos, what string) *ast.Ident {
	l.ntemp++
	return &ast.Ident{NamePos: pos, Name: fmt.Sprintf("%s%s%d", tempPrefix, what, l.ntemp)}
}

// ----------------------------------------------------------------------------
// Declarations

func (l *lowerer) decl(d ast.Decl) {
	switch d := d.(type) {
	case *ast.FuncDecl:
		if d.Body == nil {
			return
		}
		d.Arrow = token.NoPos // print the body as a block
		saved := l.fn
		if obj, _ := l.info.Defs[d.Name].(*types.Func); obj != nil {
			l.fn = obj.Signature()
		}
		d.Body.List = l.stmts(d.Body.List)
		l.fn = saved
	case *ast.GenDecl:
		for _, spec := range d.Specs {
			if ts, ok := spec.(*ast.TypeSpec); ok {
				if et, ok := ts.Type.(*ast.EnumType); ok {
					l.enumDecl(ts, et)
				}
			}
			if vs, ok := spec.(*ast.ValueSpec); ok {
				var pre []ast.Stmt
				vs.Values = l.spread(l.exprList(vs.Values, &pre))
				if len(pre) > 0 {
					l.errorf(vs.Pos(), "internal error: package-level initializer needs statements")
				}
			}
		}
	}
}

// ----------------------------------------------------------------------------
// Statements

func (l *lowerer) stmts(list []ast.Stmt) []ast.Stmt {
	var out []ast.Stmt
	for _, s := range list {
		out = append(out, l.stmt(s)...)
	}
	return out
}

func (l *lowerer) block(b *ast.BlockStmt) {
	if b != nil {
		b.List = l.stmts(b.List)
	}
}

// stmt lowers s into the statements that replace it: any statements its
// expressions need, then s itself.
func (l *lowerer) stmt(s ast.Stmt) []ast.Stmt {
	var pre []ast.Stmt
	switch s := s.(type) {
	case *ast.ExprStmt:
		if t, ok := ast.Unparen(s.X).(*ast.TryExpr); ok {
			l.try(t, &pre, true)
			return pre
		}
		s.X = l.expr(s.X, &pre)

	case *ast.AssignStmt:
		for i, x := range s.Lhs {
			s.Lhs[i] = l.expr(x, &pre)
		}
		s.Rhs = l.spread(l.exprList(s.Rhs, &pre))

	case *ast.DeclStmt:
		if gd, ok := s.Decl.(*ast.GenDecl); ok {
			for _, spec := range gd.Specs {
				if vs, ok := spec.(*ast.ValueSpec); ok {
					vs.Values = l.spread(l.exprList(vs.Values, &pre))
				}
			}
		}

	case *ast.ReturnStmt:
		s.Results = l.spread(l.exprList(s.Results, &pre))

	case *ast.IncDecStmt:
		s.X = l.expr(s.X, &pre)

	case *ast.SendStmt:
		xs := l.exprList([]ast.Expr{s.Chan, s.Value}, &pre)
		s.Chan, s.Value = xs[0], xs[1]

	case *ast.GoStmt:
		l.callParts(s.Call, &pre)

	case *ast.DeferStmt:
		l.callParts(s.Call, &pre)

	case *ast.LabeledStmt:
		inner := l.stmt(s.Stmt)
		last := inner[len(inner)-1]
		if b, ok := last.(*ast.BlockStmt); ok && l.wrapped[b] {
			// label the statement inside the block lowering added
			n := len(b.List) - 1
			s.Stmt = b.List[n]
			b.List[n] = s
			return inner
		}
		s.Stmt = last
		return append(inner[:len(inner)-1], s)

	case *ast.BlockStmt:
		l.block(s)

	case *ast.IfStmt:
		return l.ifStmt(s)

	case *ast.SwitchStmt:
		if s.Tag != nil && types.EnumOf(l.info.Types[s.Tag].Type) != nil {
			return l.enumSwitch(s)
		}
		var init []ast.Stmt
		if s.Init != nil {
			init = l.stmt(s.Init)
		}
		var tagPre []ast.Stmt
		if s.Tag != nil {
			s.Tag = l.expr(s.Tag, &tagPre)
		}
		for _, c := range s.Body.List {
			cc := c.(*ast.CaseClause)
			var casePre []ast.Stmt
			for i, x := range cc.List {
				cc.List[i] = l.expr(x, &casePre)
			}
			if len(casePre) > 0 {
				l.errorf(cc.Pos(), "? cannot be used in a case expression")
			}
			cc.Body = l.stmts(cc.Body)
		}
		return l.withInit(s, &s.Init, init, tagPre)

	case *ast.TypeSwitchStmt:
		var init []ast.Stmt
		if s.Init != nil {
			init = l.stmt(s.Init)
		}
		var assignPre []ast.Stmt
		switch a := s.Assign.(type) {
		case *ast.AssignStmt:
			if ta, ok := a.Rhs[0].(*ast.TypeAssertExpr); ok {
				ta.X = l.expr(ta.X, &assignPre)
			}
		case *ast.ExprStmt:
			if ta, ok := a.X.(*ast.TypeAssertExpr); ok {
				ta.X = l.expr(ta.X, &assignPre)
			}
		}
		for _, c := range s.Body.List {
			cc := c.(*ast.CaseClause)
			cc.Body = l.stmts(cc.Body)
		}
		return l.withInit(s, &s.Init, init, assignPre)

	case *ast.SelectStmt:
		// Channel and send operands are evaluated on entering select.
		for _, c := range s.Body.List {
			cc := c.(*ast.CommClause)
			switch comm := cc.Comm.(type) {
			case *ast.SendStmt:
				xs := l.exprList([]ast.Expr{comm.Chan, comm.Value}, &pre)
				comm.Chan, comm.Value = xs[0], xs[1]
			case *ast.ExprStmt:
				l.recvOperand(comm.X, &pre)
			case *ast.AssignStmt:
				l.recvOperand(comm.Rhs[0], &pre)
			}
			cc.Body = l.stmts(cc.Body)
		}

	case *ast.ForStmt:
		var init []ast.Stmt
		if s.Init != nil {
			init = l.stmt(s.Init)
			s.Init = init[len(init)-1]
			pre = init[:len(init)-1]
		}
		if s.Post != nil {
			post := l.stmt(s.Post)
			if len(post) > 1 {
				l.errorf(s.Post.Pos(), "? cannot be used in the post statement of a for loop")
			}
			s.Post = post[len(post)-1]
		}
		l.block(s.Body)
		if s.Cond != nil {
			var condPre []ast.Stmt
			cond := l.expr(s.Cond, &condPre)
			if len(condPre) > 0 {
				// for init; cond; post { body } becomes
				// for init; ; post { pre; if !(cond) { break }; body }
				brk := &ast.IfStmt{
					If:   s.Cond.Pos(),
					Cond: &ast.UnaryExpr{OpPos: s.Cond.Pos(), Op: token.NOT, X: &ast.ParenExpr{Lparen: s.Cond.Pos(), X: cond, Rparen: s.Cond.End()}},
					Body: &ast.BlockStmt{Lbrace: s.Cond.Pos(), List: []ast.Stmt{&ast.BranchStmt{TokPos: s.Cond.Pos(), Tok: token.BREAK}}, Rbrace: s.Cond.End()},
				}
				s.Body.List = slices.Concat(condPre, []ast.Stmt{brk}, s.Body.List)
				s.Cond = nil
			} else {
				s.Cond = cond
			}
		}

	case *ast.RangeStmt:
		s.X = l.expr(s.X, &pre)
		l.block(s.Body)
	}
	return append(pre, s)
}

// recvOperand lowers the channel operand of a receive in a select case.
func (l *lowerer) recvOperand(x ast.Expr, pre *[]ast.Stmt) {
	if u, ok := ast.Unparen(x).(*ast.UnaryExpr); ok && u.Op == token.ARROW {
		u.X = l.expr(u.X, pre)
	}
}

// callParts lowers the function and arguments of a go or defer statement
// (evaluated when the statement runs) without evaluating the call.
func (l *lowerer) callParts(call *ast.CallExpr, pre *[]ast.Stmt) {
	xs := l.exprList(append([]ast.Expr{call.Fun}, call.Args...), pre)
	call.Fun = xs[0]
	call.Args = l.spread(xs[1:])
}

// ifStmt lowers an if statement, including else-if chains.
func (l *lowerer) ifStmt(s *ast.IfStmt) []ast.Stmt {
	binds := l.bindings(s.Cond, s.Body, s)
	var init []ast.Stmt
	if s.Init != nil {
		init = l.stmt(s.Init)
	}
	var condPre []ast.Stmt
	s.Cond = l.expr(s.Cond, &condPre)
	l.block(s.Body)
	switch e := s.Else.(type) {
	case *ast.IfStmt:
		if list := l.ifStmt(e); len(list) > 1 {
			s.Else = &ast.BlockStmt{Lbrace: e.Pos(), List: list, Rbrace: e.End()}
		} else {
			s.Else = list[0]
		}
	case *ast.BlockStmt:
		l.block(e)
	}
	return l.wrapBindings(binds, l.withInit(s, &s.Init, init, condPre))
}

// withInit reassembles a statement with an init statement (if, switch)
// after lowering: init holds the lowered init statement (prelude first),
// and condPre the statements its condition or tag needs.
func (l *lowerer) withInit(s ast.Stmt, initField *ast.Stmt, init, condPre []ast.Stmt) []ast.Stmt {
	if len(condPre) == 0 {
		if len(init) == 0 {
			return []ast.Stmt{s}
		}
		*initField = init[len(init)-1]
		return append(init[:len(init)-1], s)
	}
	// The condition needs statements, which must run after the init
	// statement: { init; pre; if cond { ... } }
	*initField = nil
	b := &ast.BlockStmt{Lbrace: s.Pos(), List: slices.Concat(init, condPre, []ast.Stmt{s}), Rbrace: s.End()}
	l.wrapped[b] = true
	return []ast.Stmt{b}
}

// ----------------------------------------------------------------------------
// Expressions

// spread replaces placeholders for multi-valued x? expressions in a list
// by their values.
func (l *lowerer) spread(list []ast.Expr) []ast.Expr {
	if len(list) == 1 {
		if id, ok := list[0].(*ast.Ident); ok {
			if vals, ok := l.tuples[id]; ok {
				return vals
			}
		}
	}
	return list
}

// exprList lowers a list of expressions evaluated left to right. If an
// expression needs statements, earlier expressions with calls are first
// evaluated into temporaries, so the calls still happen in order.
func (l *lowerer) exprList(list []ast.Expr, pre *[]ast.Stmt) []ast.Expr {
	if len(list) == 0 {
		return list
	}
	out := make([]ast.Expr, len(list))
	for i, x := range list {
		mark := len(*pre)
		out[i] = l.expr(x, pre)
		if len(*pre) == mark {
			continue
		}
		var spills []ast.Stmt
		for j := range i {
			if out[j] != nil && l.hasCall(out[j]) {
				t := l.temp(out[j].Pos(), "t")
				spills = append(spills, define([]ast.Expr{t}, []ast.Expr{out[j]}))
				out[j] = ident(t)
			}
		}
		if len(spills) > 0 {
			*pre = slices.Insert(*pre, mark, spills...)
		}
	}
	return out
}

// expr lowers x, appending statements that must run before it to pre.
func (l *lowerer) expr(x ast.Expr, pre *[]ast.Stmt) ast.Expr {
	switch x := x.(type) {
	case nil:
		return nil

	case *ast.TernaryExpr:
		return l.ternary(x, pre)

	case *ast.TryExpr:
		return l.try(x, pre, false)

	case *ast.LambdaExpr:
		return l.lambda(x)

	case *ast.FuncLit:
		saved := l.fn
		if sig, ok := l.info.Types[x].Type.(*types.Signature); ok {
			l.fn = sig
		}
		l.block(x.Body)
		l.fn = saved
		return x

	case *ast.CompositeLit:
		// Keys and values in order (struct field names are left alone).
		var parts []ast.Expr
		for _, e := range x.Elts {
			if kv, ok := e.(*ast.KeyValueExpr); ok {
				parts = append(parts, kv.Key, kv.Value)
			} else {
				parts = append(parts, e)
			}
		}
		parts = l.exprList(parts, pre)
		i := 0
		for k, e := range x.Elts {
			if kv, ok := e.(*ast.KeyValueExpr); ok {
				kv.Key, kv.Value = parts[i], parts[i+1]
				i += 2
			} else {
				x.Elts[k] = parts[i]
				i++
			}
		}
		return x

	case *ast.ParenExpr:
		x.X = l.expr(x.X, pre)
		return x

	case *ast.SelectorExpr:
		if v := l.variantOf(x); v != nil {
			return l.variantValue(x, v)
		}
		x.X = l.expr(x.X, pre)
		return x

	case *ast.IsExpr:
		return l.isExpr(x, pre)

	case *ast.IndexExpr:
		xs := l.exprList([]ast.Expr{x.X, x.Index}, pre)
		x.X, x.Index = xs[0], xs[1]
		return x

	case *ast.IndexListExpr:
		xs := l.exprList(append([]ast.Expr{x.X}, x.Indices...), pre)
		x.X, x.Indices = xs[0], xs[1:]
		return x

	case *ast.SliceExpr:
		xs := l.exprList([]ast.Expr{x.X, x.Low, x.High, x.Max}, pre)
		x.X, x.Low, x.High, x.Max = xs[0], xs[1], xs[2], xs[3]
		return x

	case *ast.TypeAssertExpr:
		x.X = l.expr(x.X, pre)
		return x

	case *ast.CallExpr:
		if v := l.variantOf(x.Fun); v != nil {
			// T.V(value)
			return l.construct(l.info.Types[x].Type, v, l.expr(x.Args[0], pre), x.Pos())
		}
		xs := l.exprList(append([]ast.Expr{x.Fun}, x.Args...), pre)
		x.Fun = xs[0]
		x.Args = l.spread(xs[1:])
		return x

	case *ast.StarExpr:
		x.X = l.expr(x.X, pre)
		return x

	case *ast.UnaryExpr:
		x.X = l.expr(x.X, pre)
		return x

	case *ast.BinaryExpr:
		if x.Op == token.LAND || x.Op == token.LOR {
			return l.shortCircuit(x, pre)
		}
		xs := l.exprList([]ast.Expr{x.X, x.Y}, pre)
		x.X, x.Y = xs[0], xs[1]
		return x

	case *ast.KeyValueExpr:
		xs := l.exprList([]ast.Expr{x.Key, x.Value}, pre)
		x.Key, x.Value = xs[0], xs[1]
		return x
	}
	// identifiers, literals, types
	return x
}

// shortCircuit lowers a && b or a || b. If b needs statements, they must
// only run when b is evaluated:
//
//	c := a; if c { pre(b); c = b }     (a || b: if !c)
func (l *lowerer) shortCircuit(x *ast.BinaryExpr, pre *[]ast.Stmt) ast.Expr {
	x.X = l.expr(x.X, pre)
	var yPre []ast.Stmt
	y := l.expr(x.Y, &yPre)
	if len(yPre) == 0 {
		x.Y = y
		return x
	}
	c := l.temp(x.OpPos, "c")
	var cond ast.Expr = ident(c)
	if x.Op == token.LOR {
		cond = &ast.UnaryExpr{OpPos: x.OpPos, Op: token.NOT, X: ident(c)}
	}
	// The temporary gets the type of the whole expression.
	var init ast.Expr = x.X
	if t := l.info.Types[x].Type; t != nil {
		if b, ok := t.(*types.Basic); !ok || b.Info()&types.IsUntyped == 0 {
			init = &ast.CallExpr{Fun: l.typeExpr(t, x.Pos()), Lparen: x.Pos(), Args: []ast.Expr{x.X}, Rparen: x.Pos()}
		}
	}
	*pre = append(*pre,
		define([]ast.Expr{c}, []ast.Expr{init}),
		&ast.IfStmt{If: x.OpPos, Cond: cond, Body: &ast.BlockStmt{Lbrace: x.OpPos, List: append(yPre, assign([]ast.Expr{ident(c)}, []ast.Expr{y})), Rbrace: x.End()}},
	)
	return ident(c)
}

// ternary lowers cond ? a : b.
func (l *lowerer) ternary(x *ast.TernaryExpr, pre *[]ast.Stmt) ast.Expr {
	typ := l.info.Types[x].Type
	if typ == nil {
		l.errorf(x.Pos(), "internal error: ternary expression without type")
		return x
	}
	typ = types.Default(typ)
	binds := l.bindings(x.Cond, x.X, x)
	if len(binds) > 0 {
		// The condition binds names: it is evaluated after their
		// declarations, in the function literal or statements below.
		var condPre []ast.Stmt
		cond := l.expr(x.Cond, &condPre)
		var aPre, bPre []ast.Stmt
		a := l.expr(x.X, &aPre)
		b := l.expr(x.Y, &bPre)
		return l.ternaryStmts(x, typ, slices.Concat(binds, condPre), cond, a, b, aPre, bPre, pre)
	}
	cond := l.expr(x.Cond, pre)
	var aPre, bPre []ast.Stmt
	a := l.expr(x.X, &aPre)
	b := l.expr(x.Y, &bPre)
	return l.ternaryStmts(x, typ, nil, cond, a, b, aPre, bPre, pre)
}

// ternaryStmts finishes lowering a ternary expression. head holds
// statements to run before the condition (inside the function literal of
// the simple form).
func (l *lowerer) ternaryStmts(x *ast.TernaryExpr, typ types.Type, head []ast.Stmt, cond, a, b ast.Expr, aPre, bPre []ast.Stmt, pre *[]ast.Stmt) ast.Expr {
	pos := x.Pos()
	if len(aPre) == 0 && len(bPre) == 0 {
		// func() T { head; if cond { return a }; return b }()
		lit := &ast.FuncLit{
			Type: &ast.FuncType{Func: pos, Params: &ast.FieldList{Opening: pos, Closing: pos}, Results: &ast.FieldList{List: []*ast.Field{{Type: l.typeExpr(typ, pos)}}}},
			Body: &ast.BlockStmt{Lbrace: pos, List: slices.Concat(head, []ast.Stmt{
				&ast.IfStmt{If: pos, Cond: cond, Body: &ast.BlockStmt{Lbrace: x.X.Pos(), List: []ast.Stmt{&ast.ReturnStmt{Return: x.X.Pos(), Results: []ast.Expr{a}}}, Rbrace: x.X.End()}},
				&ast.ReturnStmt{Return: x.Y.Pos(), Results: []ast.Expr{b}},
			}), Rbrace: x.End()},
		}
		return &ast.CallExpr{Fun: lit, Lparen: x.End(), Rparen: x.End()}
	}
	*pre = append(*pre, head...)

	// var t T; if cond { pre(a); t = a } else { pre(b); t = b }
	t := l.temp(pos, "v")
	*pre = append(*pre,
		&ast.DeclStmt{Decl: &ast.GenDecl{TokPos: pos, Tok: token.VAR, Specs: []ast.Spec{&ast.ValueSpec{Names: []*ast.Ident{t}, Type: l.typeExpr(typ, pos)}}}},
		&ast.IfStmt{
			If:   pos,
			Cond: cond,
			Body: &ast.BlockStmt{Lbrace: x.X.Pos(), List: append(aPre, assign([]ast.Expr{ident(t)}, []ast.Expr{a})), Rbrace: x.X.End()},
			Else: &ast.BlockStmt{Lbrace: x.Y.Pos(), List: append(bPre, assign([]ast.Expr{ident(t)}, []ast.Expr{b})), Rbrace: x.Y.End()},
		},
	)
	return ident(t)
}

// try lowers x? into
//
//	v1, ..., err := x
//	if err != nil { return zero, ..., err }
//
// appended to pre, and returns v1 (or a placeholder for v1, ..., vn). If
// discard is set, the values are not used.
func (l *lowerer) try(x *ast.TryExpr, pre *[]ast.Stmt, discard bool) ast.Expr {
	operand := l.expr(x.X, pre)
	pos := x.Question

	var n int // number of values of x.X
	switch t := l.info.Types[x.X].Type.(type) {
	case *types.Tuple:
		n = t.Len()
	case nil:
		l.errorf(x.Pos(), "internal error: ? operand without type")
		return x
	default:
		n = 1
	}

	errv := l.temp(pos, "err")
	var vals []ast.Expr
	var lhs []ast.Expr
	for range n - 1 {
		if discard {
			lhs = append(lhs, ident(&ast.Ident{NamePos: pos, Name: "_"}))
			continue
		}
		v := l.temp(pos, "v")
		vals = append(vals, ident(v))
		lhs = append(lhs, v)
	}
	lhs = append(lhs, errv)
	*pre = append(*pre, define(lhs, []ast.Expr{operand}))

	// return zero values and the error
	var results []ast.Expr
	if l.fn != nil {
		res := l.fn.Results()
		for i := range res.Len() - 1 {
			results = append(results, l.zero(res.At(i).Type(), pos))
		}
	}
	// The error context is only evaluated on failure, in the if body.
	var errResult ast.Expr = ident(errv)
	var ctxPre []ast.Stmt
	if x.Context != nil {
		errResult = l.wrapError(x.Context, l.expr(x.Context, &ctxPre), ident(errv))
	}
	results = append(results, errResult)
	*pre = append(*pre, &ast.IfStmt{
		If:   pos,
		Cond: &ast.BinaryExpr{X: ident(errv), OpPos: pos, Op: token.NEQ, Y: &ast.Ident{NamePos: pos, Name: "nil"}},
		Body: &ast.BlockStmt{Lbrace: pos, List: append(ctxPre, &ast.ReturnStmt{Return: pos, Results: results}), Rbrace: pos},
	})

	switch len(vals) {
	case 0:
		return &ast.Ident{NamePos: pos, Name: "_"} // no value: x? is a statement
	case 1:
		return vals[0]
	default:
		ph := &ast.Ident{NamePos: pos, Name: "_"}
		l.tuples[ph] = vals
		return ph
	}
}

// lambda lowers a lambda to a function literal.
func (l *lowerer) lambda(x *ast.LambdaExpr) ast.Expr {
	sig, ok := l.info.Types[x].Type.(*types.Signature)
	if !ok {
		l.errorf(x.Pos(), "internal error: lambda without type")
		return x
	}
	pos := x.Pos()
	params := &ast.FieldList{Opening: pos, Closing: x.Arrow}
	i := 0
	for _, f := range x.Params.List {
		for _, name := range f.Names {
			var typ ast.Expr
			if f.Type != nil {
				typ = f.Type
			} else {
				pt := sig.Params().At(i).Type()
				if sig.Variadic() && i == sig.Params().Len()-1 {
					typ = &ast.Ellipsis{Ellipsis: name.Pos(), Elt: l.typeExpr(pt.(*types.Slice).Elem(), name.Pos())}
				} else {
					typ = l.typeExpr(pt, name.Pos())
				}
			}
			params.List = append(params.List, &ast.Field{Names: []*ast.Ident{name}, Type: typ})
			i++
		}
	}
	var results *ast.FieldList
	if res := sig.Results(); res.Len() > 0 {
		results = &ast.FieldList{}
		for i := range res.Len() {
			results.List = append(results.List, &ast.Field{Type: l.typeExpr(res.At(i).Type(), x.Arrow)})
		}
	}

	saved := l.fn
	l.fn = sig
	defer func() { l.fn = saved }()

	body := x.Block
	if body == nil {
		var s ast.Stmt
		switch {
		case sig.Results().Len() > 0:
			s = &ast.ReturnStmt{Return: x.Body.Pos(), Results: []ast.Expr{x.Body}}
		case isCallLike(x.Body):
			s = &ast.ExprStmt{X: x.Body}
		default:
			s = assign([]ast.Expr{&ast.Ident{NamePos: x.Body.Pos(), Name: "_"}}, []ast.Expr{x.Body})
		}
		body = &ast.BlockStmt{Lbrace: x.Arrow, List: []ast.Stmt{s}, Rbrace: x.Body.End()}
	}
	l.block(body)
	return &ast.FuncLit{Type: &ast.FuncType{Func: pos, Params: params, Results: results}, Body: body}
}

func isCallLike(x ast.Expr) bool {
	switch x := ast.Unparen(x).(type) {
	case *ast.CallExpr, *ast.TryExpr:
		return true
	case *ast.UnaryExpr:
		return x.Op == token.ARROW
	}
	return false
}

// hasCall reports whether evaluating x may have side effects or observe
// them (a call or a channel receive), so it must stay in order.
func (l *lowerer) hasCall(x ast.Expr) bool {
	found := false
	ast.Inspect(x, func(n ast.Node) bool {
		if found {
			return false
		}
		switch n := n.(type) {
		case *ast.FuncLit:
			return false // not evaluated
		case *ast.CallExpr:
			if tv, ok := l.info.Types[n.Fun]; ok && tv.IsType() {
				return true // conversion
			}
			found = true
		case *ast.UnaryExpr:
			if n.Op == token.ARROW {
				found = true
			}
		}
		return !found
	})
	return found
}

// zero returns the zero value of t.
func (l *lowerer) zero(t types.Type, pos token.Pos) ast.Expr {
	switch u := types.Unalias(t).Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Info()&types.IsBoolean != 0:
			return &ast.Ident{NamePos: pos, Name: "false"}
		case u.Info()&types.IsString != 0:
			return &ast.BasicLit{ValuePos: pos, Kind: token.STRING, Value: `""`}
		case u.Info()&types.IsNumeric != 0:
			return &ast.BasicLit{ValuePos: pos, Kind: token.INT, Value: "0"}
		default: // unsafe.Pointer
			return &ast.Ident{NamePos: pos, Name: "nil"}
		}
	case *types.Pointer, *types.Slice, *types.Map, *types.Chan, *types.Signature:
		return &ast.Ident{NamePos: pos, Name: "nil"}
	case *types.Interface:
		if _, isParam := types.Unalias(t).(*types.TypeParam); !isParam {
			return &ast.Ident{NamePos: pos, Name: "nil"}
		}
	case *types.Struct, *types.Array:
		return &ast.CompositeLit{Type: l.typeExpr(t, pos), Lbrace: pos, Rbrace: pos}
	}
	// type parameters: *new(T)
	return &ast.StarExpr{Star: pos, X: &ast.CallExpr{Fun: &ast.Ident{NamePos: pos, Name: "new"}, Lparen: pos, Args: []ast.Expr{l.typeExpr(t, pos)}, Rparen: pos}}
}

