// typeExpr returns a type expression denoting t in this file.
func (l *lowerer) typeExpr(t types.Type, pos token.Pos) ast.Expr {
	id := func(name string) *ast.Ident { return &ast.Ident{NamePos: pos, Name: name} }
	switch t := t.(type) {
	case *types.Basic:
		if t.Kind() == types.UnsafePointer {
			return &ast.SelectorExpr{X: id(l.importName("unsafe")), Sel: id("Pointer")}
		}
		if t.Info()&types.IsUntyped != 0 {
			return l.typeExpr(types.Default(t), pos)
		}
		return id(t.Name())
	case *types.Named:
		return l.named(t.Obj(), t.TypeArgs(), pos)
	case *types.Alias:
		if obj := t.Obj(); obj.Pkg() == nil || obj.Pkg() == l.pkg || obj.Exported() {
			return l.named(obj, t.TypeArgs(), pos)
		}
		return l.typeExpr(types.Unalias(t), pos)
	case *types.TypeParam:
		return id(t.Obj().Name())
	case *types.Pointer:
		return &ast.StarExpr{Star: pos, X: l.typeExpr(t.Elem(), pos)}
	case *types.Slice:
		return &ast.ArrayType{Lbrack: pos, Elt: l.typeExpr(t.Elem(), pos)}
	case *types.Array:
		return &ast.ArrayType{Lbrack: pos, Len: &ast.BasicLit{ValuePos: pos, Kind: token.INT, Value: strconv.FormatInt(t.Len(), 10)}, Elt: l.typeExpr(t.Elem(), pos)}
	case *types.Map:
		return &ast.MapType{Map: pos, Key: l.typeExpr(t.Key(), pos), Value: l.typeExpr(t.Elem(), pos)}
	case *types.Chan:
		dir := ast.SEND | ast.RECV
		switch t.Dir() {
		case types.SendOnly:
			dir = ast.SEND
		case types.RecvOnly:
			dir = ast.RECV
		}
		return &ast.ChanType{Begin: pos, Arrow: pos, Dir: dir, Value: l.typeExpr(t.Elem(), pos)}
	case *types.Signature:
		return l.funcType(t, pos)
	case *types.Struct:
		fields := &ast.FieldList{Opening: pos, Closing: pos}
		for i := range t.NumFields() {
			f := t.Field(i)
			field := &ast.Field{Type: l.typeExpr(f.Type(), pos)}
			if !f.Embedded() {
				field.Names = []*ast.Ident{id(f.Name())}
			}
			if tag := t.Tag(i); tag != "" {
				field.Tag = &ast.BasicLit{ValuePos: pos, Kind: token.STRING, Value: strconv.Quote(tag)}
			}
			fields.List = append(fields.List, field)
		}
		return &ast.StructType{Struct: pos, Fields: fields}
	case *types.Interface:
		methods := &ast.FieldList{Opening: pos, Closing: pos}
		for i := range t.NumEmbeddeds() {
			methods.List = append(methods.List, &ast.Field{Type: l.typeExpr(t.EmbeddedType(i), pos)})
		}
		for i := range t.NumExplicitMethods() {
			m := t.ExplicitMethod(i)
			methods.List = append(methods.List, &ast.Field{Names: []*ast.Ident{id(m.Name())}, Type: l.funcType(m.Signature(), pos)})
		}
		return &ast.InterfaceType{Interface: pos, Methods: methods}
	case *types.Union:
		var x ast.Expr
		for i := range t.Len() {
			term := t.Term(i)
			var y ast.Expr = l.typeExpr(term.Type(), pos)
			if term.Tilde() {
				y = &ast.UnaryExpr{OpPos: pos, Op: token.TILDE, X: y}
			}
			if x == nil {
				x = y
			} else {
				x = &ast.BinaryExpr{X: x, OpPos: pos, Op: token.OR, Y: y}
			}
		}
		return x
	}
	l.errorf(pos, "internal error: cannot write type %s", t)
	return id("any")
}

func (l *lowerer) funcType(sig *types.Signature, pos token.Pos) *ast.FuncType {
	params := &ast.FieldList{Opening: pos, Closing: pos}
	for i := range sig.Params().Len() {
		pt := sig.Params().At(i).Type()
		var typ ast.Expr
		if sig.Variadic() && i == sig.Params().Len()-1 {
			typ = &ast.Ellipsis{Ellipsis: pos, Elt: l.typeExpr(pt.(*types.Slice).Elem(), pos)}
		} else {
			typ = l.typeExpr(pt, pos)
		}
		params.List = append(params.List, &ast.Field{Type: typ})
	}
	var results *ast.FieldList
	if sig.Results().Len() > 0 {
		results = &ast.FieldList{Opening: pos, Closing: pos}
		for i := range sig.Results().Len() {
			results.List = append(results.List, &ast.Field{Type: l.typeExpr(sig.Results().At(i).Type(), pos)})
		}
	}
	return &ast.FuncType{Func: pos, Params: params, Results: results}
}

// named returns an expression for the named (or alias) type obj with the
// given type arguments.
func (l *lowerer) named(obj *types.TypeName, targs *types.TypeList, pos token.Pos) ast.Expr {
	var x ast.Expr
	switch {
	case obj.Pkg() == nil || obj.Pkg() == l.pkg:
		x = &ast.Ident{NamePos: pos, Name: obj.Name()}
	case !obj.Exported():
		l.errorf(pos, "the type %s.%s is not exported, so it cannot be written here; give the expression an explicit type", obj.Pkg().Name(), obj.Name())
		x = &ast.Ident{NamePos: pos, Name: obj.Name()}
	default:
		x = &ast.SelectorExpr{X: &ast.Ident{NamePos: pos, Name: l.importName(obj.Pkg().Path())}, Sel: &ast.Ident{NamePos: pos, Name: obj.Name()}}
	}
	if targs.Len() == 0 {
		return x
	}
	var args []ast.Expr
	for i := range targs.Len() {
		args = append(args, l.typeExpr(targs.At(i), pos))
	}
	if len(args) == 1 {
		return &ast.IndexExpr{X: x, Lbrack: pos, Index: args[0], Rbrack: pos}
	}
	return &ast.IndexListExpr{X: x, Lbrack: pos, Indices: args, Rbrack: pos}
}

// importName returns the name under which lowered code refers to the
// package with the given path, adding an import for it. Lowering uses its
// own import names so that local declarations cannot shadow them.
func (l *lowerer) importName(path string) string {
	if name, ok := l.imports[path]; ok {
		return name
	}
	base := path[strings.LastIndex(path, "/")+1:]
	base = strings.Map(func(r rune) rune {
		if r == '_' || 'a' <= r && r <= 'z' || 'A' <= r && r <= 'Z' || '0' <= r && r <= '9' {
			return r
		}
		return '_'
	}, base)
	name := fmt.Sprintf("%s%s%d", tempPrefix, base, len(l.imports)+1)
	l.imports[path] = name
	return name
}

// addImports adds the imports lowering needs, after the file's imports.
func (l *lowerer) addImports() {
	if len(l.imports) == 0 {
		return
	}
	paths := make([]string, 0, len(l.imports))
	for p := range l.imports {
		paths = append(paths, p)
	}
	slices.Sort(paths)
	pos := l.file.Name.End()
	insert := 0
	for i, d := range l.file.Decls {
		if gd, ok := d.(*ast.GenDecl); ok && gd.Tok == token.IMPORT {
			pos = gd.End()
			insert = i + 1
		}
	}
	var decls []ast.Decl
	for _, p := range paths {
		spec := &ast.ImportSpec{
			Name: &ast.Ident{NamePos: pos, Name: l.imports[p]},
			Path: &ast.BasicLit{ValuePos: pos, Kind: token.STRING, Value: strconv.Quote(p)},
		}
		decls = append(decls, &ast.GenDecl{TokPos: pos, Tok: token.IMPORT, Specs: []ast.Spec{spec}})
		l.file.Imports = append(l.file.Imports, spec)
	}
	l.file.Decls = slices.Insert(l.file.Decls, insert, decls...)
}

// ----------------------------------------------------------------------------
// Helpers

func ident(id *ast.Ident) *ast.Ident { return &ast.Ident{NamePos: id.NamePos, Name: id.Name} }

func define(lhs, rhs []ast.Expr) *ast.AssignStmt {
	return &ast.AssignStmt{Lhs: lhs, TokPos: rhs[0].Pos(), Tok: token.DEFINE, Rhs: rhs}
}

func assign(lhs, rhs []ast.Expr) *ast.AssignStmt {
	return &ast.AssignStmt{Lhs: lhs, TokPos: rhs[0].Pos(), Tok: token.ASSIGN, Rhs: rhs}
}

// wrapError returns the error to return for x? context, where ctx is the
// lowered context expression orig.
func (l *lowerer) wrapError(orig, ctx, err ast.Expr) ast.Expr {
	pos := orig.Pos()
	str := func(s string) ast.Expr {
		return &ast.BasicLit{ValuePos: pos, Kind: token.STRING, Value: strconv.Quote(s)}
	}
	errorf := func(args ...ast.Expr) ast.Expr {
		fun := &ast.SelectorExpr{X: &ast.Ident{NamePos: pos, Name: l.importName("fmt")}, Sel: &ast.Ident{NamePos: pos, Name: "Errorf"}}
		return &ast.CallExpr{Fun: fun, Lparen: pos, Args: args, Rparen: pos}
	}
	tv := l.info.Types[orig]
	switch types.ErrorContextOf(tv) {
	case types.ContextMessage:
		if tv.Value != nil && tv.Value.Kind() == constant.String {
			if msg := constant.StringVal(tv.Value); !strings.Contains(msg, "%") {
				return errorf(str(msg+": %w"), err)
			}
		}
		return errorf(str("%s: %w"), ctx, err)
	case types.ContextFormat:
		return errorf(ctx, err)
	case types.ContextError:
		return errorf(str("%w: %w"), ctx, err)
	case types.ContextFunc:
		return &ast.CallExpr{Fun: primary(ctx), Lparen: pos, Args: []ast.Expr{err}, Rparen: pos}
	}
	l.errorf(pos, "internal error: error context without type")
	return err
}
